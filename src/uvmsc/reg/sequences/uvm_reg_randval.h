#ifndef UVM_REG_RANDVAL_H_
#define UVM_REG_RANDVAL_H_

#include <random>

#include <systemc>

#include "uvmsc/reg/uvm_reg_model.h"
#include "uvmsc/misc/uvm_misc.h"

namespace uvm
{

//----------------------------------------------------------------------
// Class: uvm_reg_randval
//
//! Utility class which generates the data values used by the built-in
//! register and memory test sequences.
//!
//! The values come from a pseudo-random number generator. Unless a seed
//! is set with the member function set_seed, the generator is seeded on
//! first use with uvm_create_random_seed, so the values only change
//! with the global seed (see uvm_set_random_seed).
//----------------------------------------------------------------------

class uvm_reg_randval
{
 public:

  // Data member: randval
  // The value generated by the last call of randomize
  uvm_reg_data_t randval;

  uvm_reg_randval() : randval(0), m_seeded(false)
  {}

  // Member function: randomize
  //
  // Generates a new value in randval. Always returns true.
  //
  bool randomize()
  {
    if (!m_seeded)
      set_seed(uvm_create_random_seed("uvm_reg_randval"));

    for (int lsb = 0; lsb < UVM_REG_DATA_WIDTH; lsb += 64)
    {
      int msb = (lsb + 63 < UVM_REG_DATA_WIDTH) ? lsb + 63 : UVM_REG_DATA_WIDTH - 1;
      sc_dt::uint64 bits = m_rng();
      if (msb - lsb < 63)
        bits &= (sc_dt::uint64(1) << (msb - lsb + 1)) - 1;
      randval.range(msb, lsb) = bits;
    }
    return true;
  }

  // Member function: set_seed
  //
  // Restarts the generator with the given seed.
  //
  void set_seed( unsigned long seed )
  {
    m_rng.seed(seed);
    m_seeded = true;
  }

  // Member function: has_seed
  //
  // Returns true if the generator has been seeded, by set_seed or by
  // the first call of randomize.
  //
  bool has_seed() const
  {
    return m_seeded;
  }

 private:
  std::mt19937_64 m_rng;
  bool m_seeded;

}; // class uvm_reg_randval

} // namespace uvm

#endif // UVM_REG_RANDVAL_H_
